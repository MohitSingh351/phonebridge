import AppKit
import Foundation
import Observation
import PBProtocol
import PBTransport

/// The pasteboard operations the feature needs. `NSPasteboard.general` in the app; a fake in tests.
@MainActor
public protocol Pasteboard: AnyObject {
    var changeCount: Int { get }
    /// Type identifiers of the current item (does not read contents → no privacy alert).
    var typeIdentifiers: [String] { get }
    /// Reads plain text. On macOS 15.4+ this can show the "Paste from other apps" alert.
    func readString() -> String?
    /// Replaces the contents; returns the new change count.
    func write(_ text: String) -> Int
    var accessDenied: Bool { get }
}

@MainActor
final class SystemPasteboard: Pasteboard {
    private let pb = NSPasteboard.general
    var changeCount: Int { pb.changeCount }
    var typeIdentifiers: [String] { pb.types?.map(\.rawValue) ?? [] }
    func readString() -> String? { pb.string(forType: .string) }
    func write(_ text: String) -> Int {
        pb.clearContents()
        pb.setString(text, forType: .string)
        return pb.changeCount
    }
    var accessDenied: Bool {
        if #available(macOS 15.4, *) { return pb.accessBehavior == .alwaysDeny }
        return false
    }
}

/// Clipboard sync, Mac side (PROTOCOL.md §8).
///  - Watches `changeCount` every 0.5 s (cheap, no privacy prompt) and only reads text when it changed.
///  - Never sends password-manager items (concealed/transient/auto-generated markers).
///  - Writes from the phone are ignored by the watcher (own `changeCount`) and by the sync core.
///  - If no phone is connected, the newest item waits up to 5 minutes (PROTOCOL.md §12).
@MainActor @Observable
public final class ClipboardFeature: Feature {
    public let id = "clipboard"
    public var state: CapabilityState { .available } // receiving always works; sending may need access

    /// User setting: automatically send what's copied on the Mac.
    public var autoSend: Bool {
        didSet { UserDefaults.standard.set(autoSend, forKey: "clipboard.autoSend") }
    }
    /// True when the user set PhoneBridge to "Deny" in Privacy & Security → Paste from Other Apps.
    public private(set) var accessDenied = false
    public private(set) var lastEvent: String?

    static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", // 1Password marks items this way too
    ]
    public static let pendingTTL: TimeInterval = 5 * 60

    private let core: ClipboardSyncCore
    private let pasteboard: Pasteboard
    private var links: Set<FeatureLink> = []
    private var lastSeenChange: Int
    private var ownWrite: Int?
    private var pending: (message: ClipboardSet, at: Date)?
    private var timer: Timer?
    private let now: () -> Date

    public convenience init(macDeviceId: PBUUID) {
        self.init(macDeviceId: macDeviceId, pasteboard: SystemPasteboard(), startTimer: true)
    }

    init(macDeviceId: PBUUID, pasteboard: Pasteboard, startTimer: Bool, now: @escaping () -> Date = { Date() }) {
        core = ClipboardSyncCore(myDeviceId: macDeviceId)
        self.pasteboard = pasteboard
        self.now = now
        lastSeenChange = pasteboard.changeCount // don't send whatever was on the clipboard before launch
        autoSend = UserDefaults.standard.object(forKey: "clipboard.autoSend") as? Bool ?? true
        if startTimer {
            timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
                MainActor.assumeIsolated { self?.poll() }
            }
        }
    }

    // MARK: Feature

    public func sessionStarted(_ link: FeatureLink) {
        links.insert(link)
        if let p = pending, now().timeIntervalSince(p.at) < Self.pendingTTL {
            link.send(p.message)
            lastEvent = "Sent to \(link.device.name)"
        }
        pending = nil
    }

    public func sessionEnded(_ link: FeatureLink) { links.remove(link) }

    public func received(_ envelope: Envelope, from link: FeatureLink) {
        guard envelope.type == ClipboardSet.type,
              let msg = try? envelope.decode(ClipboardSet.self), // validates hash + size
              let text = core.onRemote(msg) else { return }
        ownWrite = pasteboard.write(text)
        lastSeenChange = ownWrite!
        lastEvent = "Copied from \(link.device.name)"
    }

    // MARK: Watching

    /// One watcher tick (internal for tests).
    func poll() {
        accessDenied = pasteboard.accessDenied
        let cc = pasteboard.changeCount
        guard cc != lastSeenChange else { return }
        lastSeenChange = cc
        if cc == ownWrite { return } // our own write from the phone
        guard autoSend, !accessDenied else { return }
        let types = Set(pasteboard.typeIdentifiers)
        guard types.isDisjoint(with: Self.skippedTypes) else { return } // password managers
        guard let text = pasteboard.readString() else { return }
        switch core.onLocalCopy(text) {
        case .send(let msg):
            if links.isEmpty {
                pending = (msg, now())
            } else {
                for l in links { l.send(msg) }
                lastEvent = "Sent to \(links.map(\.device.name).sorted().joined(separator: ", "))"
            }
        case .tooLarge:
            lastEvent = "Too large for the clipboard (over 1 MB)"
        case .cameFromOtherDevice, .alreadySent, .empty:
            break
        }
    }
}
